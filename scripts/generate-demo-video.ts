import { execFileSync } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Run with `bun scripts/generate-demo-video.ts`; requires FFmpeg with libx264.
// Native selector preflights can take longer than the old six-second clip.
// Keep real playback observable without changing the player's lifecycle rules.
const output = fileURLToPath(new URL('../src/lib/demo-video.generated.ts', import.meta.url));
const previous = await readFile(output, 'utf8');
const poster = previous.slice(previous.indexOf('// Bounded raster cover'));
if (!poster.startsWith('// Bounded raster cover')) throw new Error('Demo poster export is missing');
const directory = await mkdtemp(join(tmpdir(), 'muqun-demo-video-'));
const video = join(directory, 'sample-video.mp4');

try {
  execFileSync('ffmpeg', [
    '-hide_banner',
    '-loglevel',
    'error',
    '-f',
    'lavfi',
    '-i',
    'testsrc2=size=320x180:rate=12',
    '-f',
    'lavfi',
    '-i',
    'sine=frequency=440:sample_rate=24000',
    '-t',
    '30',
    '-c:v',
    'libx264',
    '-preset',
    'fast',
    '-crf',
    '32',
    '-pix_fmt',
    'yuv420p',
    '-threads',
    '1',
    '-c:a',
    'aac',
    '-b:a',
    '32k',
    '-movflags',
    '+faststart',
    video,
  ]);
  const encoded = (await readFile(video)).toString('base64');
  await writeFile(
    output,
    '// Generated by bun scripts/generate-demo-video.ts.\n' +
      '// Thirty seconds of H.264/AAC test-pattern media for offline native playback checks.\n' +
      `export const DEMO_VIDEO_BASE64 =\n  '${encoded}';\n\n${poster}`
  );
} finally {
  await rm(directory, { recursive: true, force: true });
}
