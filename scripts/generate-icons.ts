import { createHash } from 'node:crypto';
import { mkdtemp, readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { Font } from 'fonteditor-core';

// Nano exposes the build pipeline under its CommonJS export condition only.
const { runFontPipeline } = createRequire(import.meta.url)('react-native-nano-icons/pipeline');

const root = fileURLToPath(new URL('..', import.meta.url));
const sourceDir = join(root, 'assets/glyphs');
const outputDir = join(root, 'assets/glyphs-generated');
const tempDir = await mkdtemp(join(tmpdir(), 'muqun-icons-'));
const inputDir = join(tempDir, 'input');
const widths = [0.5, 1, 1.5, 1.8, 2, 2.2, 2.4, 2.5, 2.6, 3];

try {
  await mkdir(inputDir);
  const hash = createHash('sha256').update('nano-1.0.1;upm=1000;safeZone=1000;');
  hash.update(await readFile(fileURLToPath(import.meta.url)));
  hash.update(await readFile(join(root, 'src/icons/semantic-catalog.json')));
  const files = (await readdir(sourceDir)).filter((name) => name.endsWith('.svg')).sort();
  for (const file of files) {
    const svg = await readFile(join(sourceDir, file), 'utf8');
    const name = file.slice(0, -4);
    hash.update(file).update(svg);
    for (const width of widths) {
      await writeFile(
        join(inputDir, `${name}--${String(width).replace('.', '_')}.svg`),
        svg.replace('stroke-width="2"', `stroke-width="${width}"`)
      );
    }
    if (name === 'shift' || name === 'stop') {
      await writeFile(
        join(inputDir, `${name}--filled.svg`),
        svg.replace('fill="none"', 'fill="currentColor"')
      );
    }
  }
  hash.update(JSON.stringify(widths));
  const inputHash = hash.digest('hex');
  if (process.argv.includes('--check')) {
    const manifest = JSON.parse(await readFile(join(outputDir, 'manifest.json'), 'utf8'));
    if (manifest.inputHash !== inputHash)
      throw new Error('Icon sources changed: run bun run icons:generate');
    for (const [file, expected] of Object.entries(manifest.files)) {
      const actual = createHash('sha256')
        .update(await readFile(join(root, file)))
        .digest('hex');
      if (actual !== expected) throw new Error(`Generated icon artifact changed: ${file}`);
    }
    console.log('Generated icon sources and font/map integrity match.');
    await rm(tempDir, { recursive: true, force: true });
    process.exit(0);
  }
  const result = await runFontPipeline(
    { fontFamily: 'muqun', upm: 1000, safeZone: 1000, startUnicode: 0xe000, linking: 'dynamic' },
    { inputDir, outputDir: join(tempDir, 'output'), tempDir: join(tempDir, 'work') },
    { inputHash, concurrency: 1 }
  );
  const generatedMap: { i: Record<string, [number, [number, string][]]> } = JSON.parse(
    await readFile(result.glyphmapPath, 'utf8')
  );
  const fontBuffer = await readFile(result.ttfPath);
  const font = Font.create(fontBuffer, { type: 'ttf' }).get();
  for (const [name, [, layers]] of Object.entries(generatedMap.i)) {
    if (layers.length === 0) throw new Error(`Icon has no generated layers: ${name}`);
    for (const [codepoint] of layers) {
      const glyph = font.glyf[font.cmap[String(codepoint)]];
      if (!glyph?.contours?.length || glyph.xMax <= glyph.xMin || glyph.yMax <= glyph.yMin)
        throw new Error(`Icon has an empty generated outline: ${name}`);
    }
  }
  await mkdir(outputDir, { recursive: true });
  const fontName = `${result.family}.ttf`;
  await writeFile(join(outputDir, fontName), fontBuffer);
  await writeFile(join(outputDir, 'muqun.glyphmap.json'), await readFile(result.glyphmapPath));
  await writeFile(
    join(root, 'src/icons/font.generated.ts'),
    `// Generated by scripts/generate-icons.ts. Do not edit.\nexport const iconFont = require('../../assets/glyphs-generated/${fontName}');\n`
  );
  const catalog: Record<string, string> = JSON.parse(
    await readFile(join(root, 'src/icons/semantic-catalog.json'), 'utf8')
  );
  await writeFile(
    join(root, 'src/icons/index.tsx'),
    '// Generated from semantic-catalog.json by scripts/generate-icons.ts. Do not edit.\n' +
      "import { AppIcon, type AppIconProps } from './app-icon';\n" +
      "export type { AppIconComponent, AppIconProps } from './app-icon';\n" +
      Object.entries(catalog)
        .map(
          ([symbol, name]) =>
            `export function ${symbol}(props: AppIconProps) {\n  return <AppIcon name="${name}" {...props} />;\n}\n`
        )
        .join('')
  );
  const artifactFiles = [
    `assets/glyphs-generated/${fontName}`,
    'assets/glyphs-generated/muqun.glyphmap.json',
    'src/icons/font.generated.ts',
    'src/icons/index.tsx',
  ];
  const integrity: Record<string, string> = {};
  for (const file of artifactFiles)
    integrity[file] = createHash('sha256')
      .update(await readFile(join(root, file)))
      .digest('hex');
  await writeFile(
    join(outputDir, 'manifest.json'),
    JSON.stringify({ inputHash, files: integrity }, null, 2) + '\n'
  );
  // Keep exactly the font referenced by the generated module; old OTA bundles
  // retain their own content-addressed copy in the updater's asset storage.
  for (const file of await readdir(outputDir)) {
    if (file.endsWith('.ttf') && file !== fontName) await rm(join(outputDir, file));
  }
  console.log(`Generated ${files.length} SVG originals as ${result.family}.`);
} finally {
  await rm(tempDir, { recursive: true, force: true });
}
