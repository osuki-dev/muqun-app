// react-native-release-profiler is linked into Android debug builds only
// (`buildTypes: ['debug']` in react-native.config.js), so a release APK carries
// neither its code nor the WRITE_EXTERNAL_STORAGE its manifest asks for. But
// React Native generates one PackageList for every build type, and it names
// `com.releaseprofiler.ReleaseProfilerPackage` in release too. This gives the
// release source set an empty package of that name, so the release build
// compiles and registers nothing.
//
// A release profiling build (MUQUN_RELEASE_PROFILER=1) links the real package
// into every build type, and the stub steps aside so the class is not defined
// twice.
const fs = require('node:fs');
const path = require('node:path');
const { withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');

const STUB_DIR = 'src/releaseProfilerStub/java';
const MARKER = '// release-profiler-stub';

const STUB = `package com.releaseprofiler;

import com.facebook.react.ReactPackage;
import com.facebook.react.bridge.NativeModule;
import com.facebook.react.bridge.ReactApplicationContext;
import com.facebook.react.uimanager.ViewManager;
import java.util.Collections;
import java.util.List;

/** Generated by plugins/with-release-profiler-stub.js: registers nothing. */
public class ReleaseProfilerPackage implements ReactPackage {
  @Override
  public List<NativeModule> createNativeModules(ReactApplicationContext reactContext) {
    return Collections.emptyList();
  }

  @Override
  public List<ViewManager> createViewManagers(ReactApplicationContext reactContext) {
    return Collections.emptyList();
  }
}
`;

const GRADLE = `
${MARKER}: see plugins/with-release-profiler-stub.js
if (System.getenv('MUQUN_RELEASE_PROFILER') != '1') {
    android.sourceSets.release.java.srcDirs += '${STUB_DIR}'
}
`;

module.exports = function withReleaseProfilerStub(config) {
  config = withDangerousMod(config, [
    'android',
    (mod) => {
      const dir = path.join(
        mod.modRequest.platformProjectRoot,
        'app',
        STUB_DIR,
        'com',
        'releaseprofiler'
      );
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'ReleaseProfilerPackage.java'), STUB);
      return mod;
    },
  ]);
  return withAppBuildGradle(config, (mod) => {
    if (!mod.modResults.contents.includes(MARKER)) {
      mod.modResults.contents += GRADLE;
    }
    return mod;
  });
};
